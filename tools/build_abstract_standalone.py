# -*- coding: utf-8 -*-
"""Generate a standalone abstract PDF for each manuscript.

The abstract is NOT retyped: this script lifts the preamble and the whole
\\begin{frontmatter}...\\end{frontmatter} block verbatim out of main.tex and wraps them
in a minimal document, so the standalone page carries exactly the title, authors,
affiliation, abstract and keywords of the submitted manuscript and cannot drift from
it.  Output: paper_a1/abstract.tex + .pdf and paper_a2/abstract.tex + .pdf."""
import io
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGETS = ['paper_a1', 'paper_a2']

HEADER = ('%% GENERATED by tools/build_abstract_standalone.py from %s/main.tex -- do not edit.\n'
          '%% Edit the manuscript instead and re-run the script.\n')

for folder in TARGETS:
    main = os.path.join(ROOT, folder, 'main.tex')
    with io.open(main, encoding='utf-8') as f:
        tex = f.read()

    pre = re.search(r'(?s)^(.*?)\\begin\{document\}', tex)
    fm = re.search(r'(?s)\\begin\{frontmatter\}(.*?)\\end\{frontmatter\}', tex)
    if not pre or not fm:
        print('ABORT %s: could not find the preamble or the frontmatter block' % folder)
        sys.exit(1)

    preamble = pre.group(1).rstrip()
    frontmatter = fm.group(0)

    # The standalone page has no sections, so a cross-reference inherited from the
    # manuscript would typeset as "??".  Drop the parenthetical pointer (it is
    # meaningless outside the manuscript) and neutralise any other \ref.
    before_refs = len(re.findall(r'\\ref\{', frontmatter))
    frontmatter = re.sub(r'\s*\(\s*Section~?\\ref\{[^}]*\}\s*\)', '', frontmatter)
    frontmatter = re.sub(r'Sections?~?\\ref\{[^}]*\}', 'the manuscript', frontmatter)
    frontmatter = re.sub(r'\\ref\{[^}]*\}', 'the manuscript', frontmatter)
    after_refs = len(re.findall(r'\\ref\{', frontmatter))

    # The standalone page is not the review manuscript, so normalise the class: drop the
    # review option (which sets 1.5 line spacing) and make sure a normal page measure is
    # in force, otherwise the keywords spill onto a second page.  This touches only the
    # generated file; the manuscript preamble is left alone.
    def _cls(m):
        opts = [o.strip() for o in m.group(1).split(',') if o.strip() and o.strip() != 'review']
        return '\\documentclass%s{elsarticle}' % ('[%s]' % ','.join(opts) if opts else '')

    preamble, n = re.subn(r'\\documentclass\[([^\]]*)\]\{elsarticle\}', _cls, preamble, count=1)
    if 'geometry' not in preamble:
        preamble = re.sub(r'(\\documentclass[^\n]*\n)', r'\1\\usepackage[letterpaper,margin=1in]{geometry}\n',
                          preamble, count=1)

    out_tex = os.path.join(ROOT, folder, 'abstract.tex')
    body = (HEADER % folder) + preamble + '\n\n\\begin{document}\n' + frontmatter + '\n\\end{document}\n'
    with io.open(out_tex, 'w', encoding='utf-8', newline='\n') as f:
        f.write(body)

    ok = True
    for _ in range(2):
        r = subprocess.run(['pdflatex', '-interaction=nonstopmode', '-halt-on-error', 'abstract.tex'],
                           cwd=os.path.join(ROOT, folder), stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        if r.returncode != 0:
            ok = False
            tail = r.stdout.decode('utf-8', 'replace').strip().split('\n')[-12:]
            print('ABORT %s: pdflatex failed\n%s' % (folder, '\n'.join(tail)))
            break

    log = os.path.join(ROOT, folder, 'abstract.log')
    if ok and os.path.isfile(log):
        with io.open(log, encoding='utf-8', errors='replace') as f:
            L = f.read()
        pages = re.search(r'Output written on abstract\.pdf \((\d+) pages', L)
        errs = len(re.findall(r'(?m)^! ', L))
        print('%-10s abstract.tex/pdf written   pages %s   errors %d   size %d B   cross-refs dropped %d'
              % (folder, pages.group(1) if pages else '?', errs,
                 os.path.getsize(os.path.join(ROOT, folder, 'abstract.pdf')),
                 before_refs - after_refs))
        if errs:
            print('  WARNING: %d LaTeX error(s) in the abstract build' % errs)
    # leave abstract.aux/.log on disk (gitignored) rather than deleting them
print('done.')
