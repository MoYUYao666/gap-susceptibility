def main() -> int:
    apply = "--apply" in sys.argv
    n = 0
    for fname, old, new, label in EDITS:
        p = REPO / fname
        t = io.open(p, encoding="utf-8").read()
        if old in t:
            print(f"  ✅ 命中：{label}")
            if apply:
                io.open(p, "w", encoding="utf-8", newline="").write(t.replace(old, new, 1))
            n += 1
        else:
            print(f"  ⚠ 未命中：{label}")
    print(f"\n{n}/{len(EDITS)} 处{'已改' if apply else '可改'}")
    if apply:
        for fname, _, new, label in EDITS:
            t = io.open(REPO / fname, encoding="utf-8").read()
            probe = new.splitlines()[0][:38]
            assert probe in t, f"断言失败：{fname} 未含新文本（{label}）"
        print("✅ 断言通过：全部新文本已写入")
    else:
        print("（预演，加 --apply 生效）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
