#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""_p44l_p3_nan_probe.py -- R3.22 decisive probe, ~3 minutes instead of ~40.

The full training run is expensive because of 3 epochs x 16 samples. But the
reviewer's question can be answered far more cheaply: at the rank where the paper
observes NaN (r>=24) versus a rank where it never does (r<=20), load the exact
paper configuration and measure, at INITIALISATION (before any optimizer step):

  * per-tensor finiteness of every LoRA weight and of every LLM layer's output
    hidden state, walking the stack from input embeddings to the last layer;
  * the magnitude growth factor layer by layer;
  * the alignment energy E and the norm of dE/dtheta, per block;
  * the same quantities after ONE backward pass (gradient finiteness).

If E is already non-finite at r=24 with finite weights and finite task loss while
r<=20 is finite everywhere, the non-finiteness is generated by the energy
functional acting on an ill-conditioned geometry, not by an optimizer blow-up.

The probe also measures the fp16 dynamic-range headroom: the largest finite
magnitude actually reached, versus the fp16 maximum 65504.

Protocol otherwise identical to paper3/scripts/run_training.py (positional
20-sample window, blank 336x336 images, 4-bit nf4 + double quant, LoRA q/k/v/o,
alpha=2r, dropout 0.1, train=samples[4:], eval=samples[:4]).

Output: outputs/analysis/p3_nan_probe.json
"""
import argparse
import glob
import json
import math
import os
from datetime import datetime

os.environ.setdefault("KMP_DUPLICATE_LIB_OK", "TRUE")
os.environ.setdefault("HF_ENDPOINT", "https://hf-mirror.com")

import numpy as np
import pandas as pd
import torch
from PIL import Image
from transformers import AutoProcessor, BitsAndBytesConfig, LlavaForConditionalGeneration

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTDIR = os.path.join(ROOT, "outputs", "analysis")
MODEL_DIR = os.path.join(ROOT, "models", "llava-hf")
FP16_MAX = 65504.0


def log(m):
    print("[%s] %s" % (datetime.now().strftime("%H:%M:%S"), m), flush=True)


def fin(t):
    return bool(torch.isfinite(t).all().item())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rank", type=int, default=24)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--compute-dtype", default="float16",
                    choices=["float16", "bfloat16"])
    ap.add_argument("--tag", default="")
    a = ap.parse_args()
    tag = a.tag or ("r%d_%s" % (a.rank, a.compute_dtype))

    torch.manual_seed(a.seed)
    np.random.seed(a.seed)

    files = sorted(glob.glob(os.path.join(ROOT, "paper3", "train-*.parquet")))
    df = pd.read_parquet(files[0])
    recs = df.iloc[0:20].to_dict("records")
    log("loaded %d samples (positional window)" % len(recs))

    cdt = getattr(torch, a.compute_dtype)
    bnb = BitsAndBytesConfig(load_in_4bit=True, bnb_4bit_compute_dtype=cdt,
                             bnb_4bit_use_double_quant=True)
    log("loading LLaVA-1.5-7B (4-bit nf4, compute=%s) ..." % a.compute_dtype)
    model = LlavaForConditionalGeneration.from_pretrained(
        MODEL_DIR, quantization_config=bnb, device_map="auto")
    processor = AutoProcessor.from_pretrained(MODEL_DIR)

    from peft import LoraConfig, TaskType, get_peft_model
    cfg = LoraConfig(r=a.rank, lora_alpha=a.rank * 2,
                     target_modules=["q_proj", "k_proj", "v_proj", "o_proj"],
                     lora_dropout=0.0, bias="none", task_type=TaskType.CAUSAL_LM)
    model = get_peft_model(model, cfg)
    n_train = sum(p.numel() for p in model.parameters() if p.requires_grad)

    rec = {"tag": tag, "rank": a.rank, "seed": a.seed,
           "compute_dtype": a.compute_dtype, "n_trainable": int(n_train),
           "fp16_max": FP16_MAX, "started": datetime.now().isoformat(timespec="seconds")}

    # ---- LoRA weight finiteness / magnitude
    lora_stats = []
    for n, p in model.named_parameters():
        if "lora_" in n:
            d = p.detach().float()
            lora_stats.append({"name": n, "finite": fin(d),
                               "absmax": float(d.abs().max().item()),
                               "norm": float(d.norm().item())})
    rec["lora_weight_stats"] = {
        "n_tensors": len(lora_stats),
        "all_finite": all(x["finite"] for x in lora_stats),
        "absmax_over_all": max(x["absmax"] for x in lora_stats),
        "max_norm": max(x["norm"] for x in lora_stats),
    }

    # ---- single sample forward, walking the hidden-state stack
    blank = Image.fromarray(np.zeros((336, 336, 3), dtype=np.uint8))
    pixel_vals = processor.image_processor(blank, return_tensors="pt")["pixel_values"]
    img_tok = model.config.image_token_index
    img_tok_id = img_tok if isinstance(img_tok, int) else img_tok.item()
    s = recs[4]                      # first TRAIN sample (eval uses the first 4)
    text = "USER: %s\nASSISTANT: %s" % (s.get("instruction", ""), s.get("output", ""))
    toks = processor.tokenizer(text, return_tensors="pt", max_length=1024, truncation=True)
    ids = torch.cat([torch.full((1, 576), img_tok_id, dtype=torch.long),
                     toks["input_ids"][:, 1:]], dim=1).cuda()
    att = torch.cat([torch.ones(1, 576, dtype=torch.long),
                     toks["attention_mask"][:, 1:]], dim=1).cuda()
    pv = pixel_vals.cuda()

    model.train()
    out = model(input_ids=ids, attention_mask=att, pixel_values=pv,
                output_hidden_states=True)
    hs = out.hidden_states
    layer_stats = []
    for i, h in enumerate(hs):
        hh = h[0].detach().float()
        ok = bool(torch.isfinite(hh).all().item())
        layer_stats.append({
            "layer": i,
            "finite": ok,
            "absmax": float(hh.abs().max().item()) if ok else None,
            "absmax_finite_part": (float(hh[torch.isfinite(hh)].abs().max().item())
                                   if torch.isfinite(hh).any() else None),
            "finite_frac": float(torch.isfinite(hh).float().mean().item()),
        })
    rec["hidden_state_layers"] = {
        "n_layers": len(layer_stats),
        "all_finite": all(x["finite"] for x in layer_stats),
        "first_nonfinite_layer": next((x["layer"] for x in layer_stats if not x["finite"]), None),
        "absmax_last_layer": layer_stats[-1]["absmax"] if layer_stats else None,
        "absmax_over_layers": max([x["absmax"] for x in layer_stats if x["absmax"] is not None],
                                  default=None),
        "headroom_vs_fp16_max": (FP16_MAX / max([x["absmax"] for x in layer_stats
                                                 if x["absmax"] is not None], default=1.0)),
        "per_layer": layer_stats,
    }

    # ---- task loss
    labels = ids.clone()
    labels[labels == processor.tokenizer.pad_token_id] = -100
    lab_out = model(input_ids=ids, attention_mask=att, pixel_values=pv, labels=labels)
    loss = lab_out.loss
    rec["task_loss"] = {"value": float(loss.item()) if fin(loss) else None,
                        "finite": fin(loss)}

    # ---- alignment energy on the SAME forward (matches the paper's formula)
    h_last = hs[-1]
    lh = h_last[0]
    ids0 = ids[0]
    vm = torch.zeros_like(ids0, dtype=torch.bool); vm[:576] = True
    pad = processor.tokenizer.pad_token_id
    lm = torch.zeros_like(ids0, dtype=torch.bool)
    lm[576:] = (ids0[576:] != pad)
    hv = lh[vm].mean(0) if fin(lh) else None
    hl = lh[lm].mean(0) if fin(lh) else None
    E = float(((hv - hl) ** 2).sum().item()) if (hv is not None and hl is not None
                                                 and fin(hv) and fin(hl)) else None
    rec["alignment_energy"] = {
        "E": E, "finite": (E is not None and math.isfinite(E)),
        "h_vis_finite": (fin(hv) if hv is not None else None),
        "h_lang_finite": (fin(hl) if hl is not None else None),
        "h_vis_absmax": (float(hv.abs().max().item()) if hv is not None and fin(hv) else None),
        "h_lang_absmax": (float(hl.abs().max().item()) if hl is not None and fin(hl) else None),
    }

    # ---- one backward pass: gradient finiteness per block
    if E is not None and math.isfinite(E):
        model.zero_grad(set_to_none=True)
        torch.tensor(E, requires_grad=False)
        # rebuild the graph so we can backward on E
        model.zero_grad(set_to_none=True)
        out2 = model(input_ids=ids, attention_mask=att, pixel_values=pv,
                     output_hidden_states=True)
        lh2 = out2.hidden_states[-1][0]
        E2 = ((lh2[vm].mean(0) - lh2[lm].mean(0)) ** 2).sum()
        E2.backward()
        gn, gn_finite = {}, True
        for name, p in model.named_parameters():
            if not p.requires_grad or p.grad is None:
                continue
            key = ("vision" if "vision_tower" in name else
                   ("proj" if "multi_modal_projector" in name else "llm"))
            g = p.grad.detach()
            if not fin(g):
                gn_finite = False
                gn[key] = None
            elif gn.get(key) is not None or key not in gn:
                gn[key] = (gn.get(key) or 0.0) + float(g.float().pow(2).sum().item())
        gn = {k: (math.sqrt(v) if v is not None else None) for k, v in gn.items()}
        rec["grad_norm_on_E"] = {"by_block": gn, "all_finite": gn_finite}
    else:
        rec["grad_norm_on_E"] = {"by_block": None, "all_finite": None,
                                 "note": "E itself non-finite; backward not attempted"}

    rec["gpu"] = torch.cuda.get_device_name(0)
    rec["finished"] = datetime.now().isoformat(timespec="seconds")

    dst = os.path.join(OUTDIR, "p3_nan_probe.json")
    prev = []
    if os.path.exists(dst):
        try:
            prev = json.load(open(dst, encoding="utf-8")).get("probes", [])
        except Exception:
            prev = []
    prev = [p for p in prev if p.get("tag") != tag] + [rec]
    with open(dst, "w", encoding="utf-8") as f:
        json.dump({"meta": {
            "script": "tools/_p44l_p3_nan_probe.py",
            "task": "task-11 (P3 R3.22, GPU probe)",
            "protocol": ("paper3/scripts/run_training.py configuration at "
                         "INITIALISATION: 20-sample positional window, blank 336x336 "
                         "image, 4-bit nf4 + double quant, LoRA q/k/v/o alpha=2r, "
                         "no optimizer step is taken"),
            "reading": ("if hidden states and loss are finite but E is not, the "
                        "non-finiteness is produced by the energy functional on an "
                        "ill-conditioned geometry, not by an optimizer blow-up")},
            "probes": prev}, f, indent=1, ensure_ascii=False)

    log("rank=%d %s: hidden all_finite=%s first_bad_layer=%s | loss=%s | E=%s | grad_all_finite=%s"
        % (a.rank, a.compute_dtype, rec["hidden_state_layers"]["all_finite"],
           rec["hidden_state_layers"]["first_nonfinite_layer"], rec["task_loss"]["value"],
           rec["alignment_energy"]["E"], rec["grad_norm_on_E"]["all_finite"]))
    log("  hidden absmax over layers=%s ; fp16 headroom=%.1fx"
        % (rec["hidden_state_layers"]["absmax_over_layers"],
           rec["hidden_state_layers"]["headroom_vs_fp16_max"]))
    log("DONE -> %s" % dst)


if __name__ == "__main__":
    main()
