def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()
    missing = [f for f in FILES if not os.path.exists(os.path.join(REPO, f))]
    print(f"  files to stage: {len(FILES)} | missing: {missing if missing else 'none'}")
    assert not missing, "refusing to stage an incomplete set"
    if not os.path.isdir(MIRROR):
        print("  !! publish_clean/ not found")
        return 1
    if not a.apply:
        print("  (dry run; nothing copied, no commit, no push)")
        return 0
    copied = 0
    for rel in FILES:
        src = os.path.join(REPO, rel)
        dst = os.path.join(MIRROR, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(src, dst)
        copied += 1
    print(f"  copied {copied} files into publish_clean/ (NOT committed, NOT pushed)")
    print("\n  review:")
    print("    git -C publish_clean status --short")
    print("    git -C publish_clean diff --stat")
    print("  then, once the submission is confirmed:")
    print('    git -C publish_clean add -A && git -C publish_clean commit -m "Add A1 revision analyses" '
          '&& git -C publish_clean push ssh-origin main')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
