# -*- coding: utf-8 -*-
r"""Read the generator of ode_ledger.json and re-run it, to see whether 96 or 103 is right.

outputs/analysis/ode_ledger.json is regenerated by a script; if the seven missing runs come from
files that still exist, re-running the generator should restore n = 103 and the paper's 222. If
they come from superseded or deleted runs, then 215 is the honest current number.

    python tools/_p728_regenerate_ledger.py [--dry-run|--apply]
"""
from __future__ import annotations

import argparse
import io
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
GEN = REPO / "tools" / "_p1_ledger.py"
PUB = REPO / "publish_clean"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()
    if not (a.dry_run or a.apply):
        a.dry_run = True
    if not GEN.exists():
        print(f"  generator not found: {GEN}")
        return 1
    t = GEN.read_text(encoding="utf-8", errors="replace")
    print(f"  {GEN.name}: {len(t.splitlines())} lines")
    print()
    print("  how it selects runs:")
    for m in re.finditer(r".{0,140}(glob|rglob|listdir|iterdir|includes|INCLUDE|WHERE|where).{0,180}",
                         t, re.S):
        seg = " ".join(m.group(0).split())
        print("     " + seg[:260])
    print()
    print("  output path and count reporting:")
    for m in re.finditer(r".{0,140}(ode_ledger\.json|n_runs_total|len\(runs\)).{0,160}", t, re.S):
        print("     " + " ".join(m.group(0).split())[:260])
    print()
    before = json.loads((PUB / "outputs/analysis/ode_ledger.json").read_text(
        encoding="utf-8", errors="ignore"))
    print(f"  ledger now: {len(before.get('runs') or [])} runs, "
          f"n_runs_total={before.get('n_runs_total')}")
    if a.apply:
        print()
        print("  running the generator...")
        r = subprocess.run([sys.executable, str(GEN), "--apply"], cwd=str(REPO),
                           capture_output=True)
        out = r.stdout.decode("utf-8", errors="replace")
        print(f"  rc={r.returncode}")
        for l in out.splitlines()[-12:]:
            print("     " + l[:150])
        after = json.loads((PUB / "outputs/analysis/ode_ledger.json").read_text(
            encoding="utf-8", errors="ignore"))
        print()
        print(f"  ledger after: {len(after.get('runs') or [])} runs, "
              f"n_runs_total={after.get('n_runs_total')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
