r"""File the review and decision documents under docs/reviews/ and write the index.

Operator instruction (2026-10-15): "记得保存这个文件在workspace并整理文件夹，不删除任何文件".

What this does:

1. copies the operator's P1 rejection letter off the Desktop into the workspace, byte for byte, and
   verifies the copy against the source SHA-256;
2. copies the two visible top-level loose files in docs/_inbox into a per-manuscript layout under
   docs/reviews/, so a reader can find them by manuscript id instead of by inbox order;
3. writes docs/reviews/README.md, the index that records for every file its original path and hash.

What this deliberately does NOT do:

* it does not delete or move the source on the Desktop;
* it does not touch the insides of docs/_inbox. Six existing tools hard-code
  `docs/_inbox/P3_reviews/_reviews.txt` (tools/_p410, _p411, _p461, _p532, _p546, and the record
  script _p417), and three of them rebuild the P3 revision package from that path. Renaming it would
  break reproducible rebuilds of a package that has already been submitted, so the legacy layout
  stays and docs/reviews/README.md records why.

Every copy is verified by SHA-256 after the write; the script is idempotent and safe to re-run.

    python tools/_p855_file_review_docs.py [--apply]
"""
from __future__ import annotations

import argparse
import hashlib
import io
import shutil
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DESKTOP = Path(r"C:\Users\hongr\Desktop\PR_reject.txt")
INBOX = REPO / "docs" / "_inbox"
REVIEWS = REPO / "docs" / "reviews"

# source -> destination, with a short role note for the index
FILES = [
    (DESKTOP, REVIEWS / "P1_PR-D-26-10149_reviews.txt", "P1 rejection letter, copied from the Desktop"),
    (INBOX / "NEUNET-D-26-09426.pdf", REVIEWS / "A1_NEUNET-D-26-09426" / "submission.pdf",
     "A1 transfer manuscript as generated by the submission system"),
    (INBOX / "_extract.txt", REVIEWS / "A1_NEUNET-D-26-09426" / "submission_extract.txt",
     "layout-preserving text extraction of the PDF above"),
    (INBOX / "P3_reviews" / "PRL Revison.txt", REVIEWS / "P3_PRLETTERS-D-26-02378" / "editor_decision.txt",
     "P3 editor decision email"),
    (INBOX / "P3_reviews" / "PRLETTERS-D-26-02378-reviews.pdf",
     REVIEWS / "P3_PRLETTERS-D-26-02378" / "reviewer_reports.pdf", "P3 reviewer reports"),
    (INBOX / "P3_reviews" / "_reviews.txt", REVIEWS / "P3_PRLETTERS-D-26-02378" / "reviewer_reports_extract.txt",
     "text extraction of the reviewer reports above"),
]


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def rel(p: Path) -> str:
    try:
        return p.relative_to(REPO).as_posix()
    except ValueError:
        return str(p)


def build_index(rows: list[tuple[Path, Path, str]]) -> str:
    lines = [
        "# Review and decision documents",
        "",
        "Index of the reviewer correspondence kept in this workspace, filed by manuscript id. Created",
        "2026-10-15 by `tools/_p855_file_review_docs.py`, which is idempotent and can be re-run.",
        "",
        "Every file below is a byte-for-byte copy of its source; the SHA-256 of each side was compared",
        "after writing. Nothing was deleted or moved out of `docs/_inbox/`.",
        "",
        "| manuscript | file | role | copied from | SHA-256 |",
        "|---|---|---|---|---|",
    ]
    for src, dst, role in rows:
        if not dst.exists():
            continue
        lines.append(f"| {dst.parent.name if dst.parent != REVIEWS else 'Paper A / P1'} "
                     f"| `{dst.name}` | {role} | `{rel(src)}` | `{sha256(dst)[:16]}…` |")
    lines += [
        "",
        "## Why `docs/_inbox/` is left as it is",
        "",
        "The legacy inbox keeps its original layout because six tools hard-code paths inside it:",
        "",
        "* `tools/_p410_parse_p3_reviews.py` and `tools/_p411_parse_p3_reviews_fixed.py` read",
        "  `docs/_inbox/P3_reviews/_reviews.txt`;",
        "* `tools/_p461_backup_prl_response.py` and `tools/_p532_regen_revision_package.py` copy three",
        "  files out of `docs/_inbox/P3_reviews/` when rebuilding the submitted P3 revision package;",
        "* `tools/_p546_parse_review_structure.py` reads the same extraction;",
        "* `tools/_p417_record_p3_revise.py` records the `docs/_inbox/P3_reviews/` path in the handoff.",
        "",
        "Renaming the directory would break the reproducible rebuild of a package that has already been",
        "submitted to Pattern Recognition Letters, so the new layout was added alongside it instead. The",
        "`P3_reviews/` subdirectory also holds a superseded extraction copy",
        "(`_superseded_...`, recorded in `HANDOFF.md`), which is likewise left in place.",
        "",
        "## Copies kept deliberately",
        "",
        "`P1_PR-D-26-10149/` holds one extra copy (`_source/PR_reject.txt`) that is byte-identical to the",
        "other two. It is kept as the pristine original so that the index's provenance claim can be",
        "checked without reaching outside the workspace.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()

    missing = [str(src) for src, _, _ in FILES if not src.exists()]
    assert not missing, f"source file(s) not found: {missing}"
    if not a.apply:
        print("  (dry run)")
        for src, dst, _ in FILES:
            print(f"  {src.name} -> {rel(dst)}")
        return 0

    REVIEWS.mkdir(parents=True, exist_ok=True)
    for src, dst, _role in FILES:
        dst.parent.mkdir(parents=True, exist_ok=True)
        if dst.exists() and sha256(dst) == sha256(src):
            print(f"  already identical: {rel(dst)}")
            continue
        shutil.copy2(src, dst)
        assert sha256(dst) == sha256(src), f"copy mismatch for {rel(dst)}"
        print(f"  copied {src.name} -> {rel(dst)}  ({dst.stat().st_size:,} bytes)")

    # the pristine source copy, so provenance can be verified without leaving the workspace
    src_copy = REVIEWS / "P1_PR-D-26-10149" / "_source" / "PR_reject.txt"
    src_copy.parent.mkdir(parents=True, exist_ok=True)
    if not src_copy.exists():
        shutil.copy2(DESKTOP, src_copy)
    assert sha256(src_copy) == sha256(DESKTOP), "source copy mismatch"

    index = build_index(FILES)
    io.open(REVIEWS / "README.md", "w", encoding="utf-8", newline="").write(index)
    print(f"  wrote {rel(REVIEWS / 'README.md')} ({len(index.splitlines())} lines)")

    # record the source file's identity in the index so the claim is checkable later
    print(f"  source SHA-256 (Desktop) = {sha256(DESKTOP)}")
    print(f"  workspace copy  SHA-256   = {sha256(REVIEWS / 'P1_PR-D-26-10149_reviews.txt')}")
    print(f"  inbox files unchanged    = {sorted(p.name for p in INBOX.iterdir())}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
