# -*- coding: utf-8 -*-
"""
P1 patch A11: make paper/scripts/gsnr_analysis.py reproducible and fix the panel-B title.

Two defects found by the audit:
  * the panel-B title asserted "Text-only matches Both (Vis grads contribute <640% to loss
    reduction)".  The percentage came from (both_final - text_final)/both_final*100, which
    is a *signed relative loss difference*, not a share of loss reduction, and it is -640
    because text-only ends at a HIGHER loss (4.15 vs 0.56).  The manuscript caption already
    states that correctly, so the title contradicted its own caption.
  * the script set no random seed, so re-running it would silently change the numbers in
    outputs/gsnr_results.json and the values quoted in the caption.

This patch adds a seed and rewrites the title from the measured losses.  The figure itself
must then be regenerated by running the script (GPU, serial with the rest).
"""
import io
import os
import shutil
import sys

ROOT = r"D:\Realdesktop\Wan\Important\New"
P = os.path.join(ROOT, "paper", "scripts", "gsnr_analysis.py")
JSON = os.path.join(ROOT, "outputs", "gsnr_results.json")
BACKUP = os.path.join(ROOT, "outputs", "gsnr_results_pre_fix.json")

EDITS = [
    # 1) deterministic seeding
    ("import matplotlib.pyplot as plt\n",
     "import matplotlib.pyplot as plt\n\n"
     "# Deterministic execution.  This script originally set no seed, so any re-run would\n"
     "# change outputs/gsnr_results.json and the values quoted in the figure caption.\n"
     "import random as _random\n"
     "SEED = 42\n"
     "_random.seed(SEED)\n"
     "np.random.seed(SEED)\n"
     "torch.manual_seed(SEED)\n"
     "if torch.cuda.is_available():\n"
     "    torch.cuda.manual_seed_all(SEED)\n"),
    # 2) the panel-B title
    ('    ax2.set_title(f"B: Text-only matches Both\\n(Vis grads contribute <{max(0, -text_advantage):.0f}% to loss reduction)", fontweight=\'bold\')',
     '    ax2.set_title("B: Text-only converges to a higher loss\\n"\n'
     '                  f"({text_final:.2f} vs. {both_final:.2f}) yet preserves alignment",\n'
     '                  fontweight=\'bold\')'),
    # 3) label the quantity for what it is
    ('    # text-only reaches similar/better loss without visual grads → visual grads are harmful\n    text_advantage = (both_final - text_final) / both_final * 100 if both_final > 0 else 0',
     '    # Signed relative loss difference, NOT a share of loss reduction: it is negative\n'
     '    # here because text-only ends at a higher loss.  Kept for traceability of the\n'
     '    # archived JSON; no longer used in any figure text.\n'
     '    text_advantage = (both_final - text_final) / both_final * 100 if both_final > 0 else 0'),
]

src = io.open(P, encoding="utf-8").read()
fails = []
for i, (old, new) in enumerate(EDITS, 1):
    n = src.count(old)
    if n != 1:
        fails.append("#%d found %d" % (i, n))
        print("FAIL #%d (%d)" % (i, n))
        continue
    src = src.replace(old, new, 1)
    print("ok   #%d" % i)
if fails:
    print(fails)
    sys.exit(1)
io.open(P, "w", encoding="utf-8", newline="").write(src)

if os.path.exists(JSON) and not os.path.exists(BACKUP):
    shutil.copy2(JSON, BACKUP)
    print("archived old results -> outputs/gsnr_results_pre_fix.json")
print("PATCH A11 APPLIED (figure must be regenerated by running the script)")
