def git_commit():
    try:
        out = subprocess.run(["git", "-C", REPO, "rev-parse", "HEAD"], capture_output=True, text=True,
                             timeout=20, check=False)
        if out.returncode == 0:
            return out.stdout.strip()
        return None
    except Exception:  # noqa: BLE001
        return None


def document_hash(doc):
    copy = json.loads(json.dumps(doc))
    copy["meta"].pop("result_sha256", None)
    canon = json.dumps(copy, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(canon.encode("utf-8")).hexdigest()


def resolve_path(doc, path):
    """Resolve a field path such as 'arms.exp_beta_paper_0.137.mean' or 'a.b[0]'.

    Plan names contain dots ('exp_beta_paper_0.137'), so a plain ``path.split('.')`` cannot be used;
    at every level the longest key the current node actually has wins.
    """
    node = doc
    rest = path
    guard = 0
    while rest:
        guard += 1
        if guard > 64:
            raise KeyError("path %r did not resolve" % path)
        if not isinstance(node, dict) or not node:
            raise KeyError("cannot descend into %r while resolving %r" % (node, path))
        # longest key that is either the whole remainder or a dotted prefix of it
        best = None
        for k in node:
            if rest == k or rest.startswith(k + ".") or rest.startswith(k + "["):
                if best is None or len(k) > len(best):
                    best = k
        if best is None:
            raise KeyError("no key matches %r while resolving %r" % (rest, path))
        node = node[best]
        rest = rest[len(best):]
        if rest.startswith("."):
            rest = rest[1:]
        if rest.startswith("["):
            close = rest.index("]")
            node = node[int(rest[1:close])]
            rest = rest[close + 1:]
            if rest.startswith("."):
                rest = rest[1:]
    return node


def serialise(doc):
    return json.dumps(doc, indent=1, ensure_ascii=False, sort_keys=False)


