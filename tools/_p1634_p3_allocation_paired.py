# -*- coding: utf-8 -*-
r"""Paired re-analysis of Paper 3's Gamma-guided vs uniform LoRA rank allocation.

What this script does
---------------------
Paper 3's weakest surviving claim is that the Gamma-guided allocation is (not) distinguishable
from a uniform allocation. An earlier bootstrap round produced a cross-paper addendum inside
``outputs/analysis/paperA_strict_bootstrap.json`` (key ``cross_paper_addendum_p3_allocation``,
generated by ``tools/_p1595_bootstrap_ci_round.py``). This script

  1. re-derives every number in that addendum from the raw archives and asserts equality
     (a non-reproducing number fails the run instead of being smoothed over), reporting for each
     number the archive file and the JSON field path it comes from;
  2. computes the full paired analysis the manuscript needs: per-arm means with sample (ddof=1)
     and population (ddof=0) sd, seed-paired differences with percentile bootstrap CIs, a
     plan-paired variant for the random pool (where the design allows it, i.e. where every plan was
     run at the same three seeds), the sign of every individual pair, TOST equivalence against a
     data-derived margin (one sample sd of the uniform arm) and the smallest equivalent margin;
  3. adds two controls -- a capacity-matched comparison (equal trainable-parameter budget, matched
     learning rate) and a matched-training-loss comparison (both arms trained at a higher learning
     rate, where the two arms' final training losses coincide) -- plus the random-allocation pool
     and the reversed rule, each with the same statistic set;
  4. writes ``outputs/analysis/p3_allocation_paired_stats.json`` with ``meta`` (script, git commit,
     archive paths, field paths, bootstrap replicate count, rng seed), ``arms``, ``paired``,
     ``equivalence``, ``controls`` and a plain-English ``conclusion``.

Archives read (field paths are recorded next to every number)
-------------------------------------------------------------
  outputs/analysis/p3_alloc_runs/<tag>/summary.json::runs.<plan>__seed<seed>   per-run delta_E, loss_last
  outputs/analysis/p3_alloc_runs/<tag>/<plan>__seed<seed>.json                 the same runs, one file each
  outputs/analysis/p3_alloc_results.json::per_plan.<plan>.delta_E              per-plan aggregates
  outputs/analysis/p3_alloc_results.json::comparisons.<plan>.vs_uniform        archived Welch test
  outputs/analysis/p3_alloc_random_pool.json::random_pool / ::gamma / ::tests  random-allocation pool
  paper3/scripts/outputs/experiments/all_results.json                          earlier LLaVA counterfactual
                                                                               groups (Theory/Random/Violation)

Two prose leaves copied out of ``p3_alloc_random_pool.json`` (``tests.levene_note`` and
``power_diagnosis.rule``) are Chinese in that archive; this archive re-emits them in English. The
field names, the nesting and every number stay identical, and each English leaf names the source
field it was translated from (see ``inherited_note`` below).

Statistics conventions
----------------------
* ``delta_E`` is the archived per-run energy change (E1 - E0 in the run record); it is never
  re-derived here from anything else, it is read straight out of the run records.
* Bootstrap: percentile method over 20000 resamples of the arithmetic mean, numpy
  ``default_rng``, per-comparison stream derived from a label hash, exactly as in
  ``tools/_p1595_bootstrap_ci_round.py`` so that the addendum numbers reproduce bit-for-bit.
* Paired bootstrap resamples the pairs together, so the pairing is inside the resample.
* TOST: two one-sided paired t-tests at alpha = 0.05 against a margin derived from the data (one
  sample sd of the uniform arm); the smallest equivalent margin is the smallest margin at which
  TOST would pass, i.e. the largest absolute endpoint of the 95% CI of the paired difference.

Output and contract
-------------------
    python tools/_p1634_p3_allocation_paired.py                 # recompute, assert, print (writes the JSON)
    python tools/_p1634_p3_allocation_paired.py --dry-run       # print the plan; write nothing
    python tools/_p1634_p3_allocation_paired.py --resamples 50000 --rng-seed 20261024

Every printed number is asserted against the JSON this script writes (the in-memory document is
re-read from disk and each ``(path, value)`` pair is checked before the number is reported as OK).
Rerunning produces a byte-identical file: there is no wall-clock value inside the hashed part, the
RNG is seeded, and ``meta.result_sha256`` is the hash of the canonical serialization of the
document without that field.

Exit status is 0 when every addendum number reproduces and every print-to-JSON assertion holds,
1 otherwise (the file is still written, so a failing number can be inspected).
"""
