def rel(path):
    return os.path.relpath(path, REPO).replace("\\", "/")


def load_json(relpath):
    with io.open(os.path.join(REPO, relpath), encoding="utf-8") as fh:
        return json.load(fh)


def load_json_readable(relpath):
    """Load a JSON that stores its foreign-language notes as raw UTF-8 (not \\uXXXX escapes).

    ``outputs/analysis/p3_alloc_random_pool.json`` (written by tools/_p458_random_pool_test.py)
    contains invalid JSON escape sequences: the Chinese notes embed a literal backslash-G. No note
    field is used as a number by this analysis, and the two notes that are copied into the output are
    re-emitted in English by ``inherited_note``, so the escape is neutralised before parsing and the
    fact is recorded in the output under ``meta.archive_repairs``.
    """
    with io.open(os.path.join(REPO, relpath), encoding="utf-8") as fh:
        raw = fh.read()
    try:
        return json.loads(raw), None
    except ValueError as exc:
        repaired = raw.replace("\\G", "G")
        doc = json.loads(repaired)
        return doc, "invalid escape sequence %r (%s); replaced '\\\\G' with 'G' before parsing" % (
            "\\G", str(exc)[:120])


def inherited_note(block, field, english):
    """Copy an archived block, re-emitting one Chinese prose leaf in English.

    ``A_POOL`` (``outputs/analysis/p3_alloc_random_pool.json``, written by
    ``tools/_p458_random_pool_test.py``) is a frozen historical archive whose ``tests.levene_note`` and
    ``power_diagnosis.rule`` leaves are Chinese. That archive keeps its Chinese: it is a pre-existing
    artefact, and the repository language rule grandfathers existing artefacts while requiring every
    newly created one to be English. This script writes a *new* archive, so the two blocks it copies
    out of ``A_POOL`` are re-emitted with those leaves translated. Only the prose changes -- the field
    name, the nesting and every number are copied verbatim -- and the English leaf names the source
    archive and field, so the translation can never be mistaken for the archived wording.
    """
    out = dict(block)
    out[field] = ("inherited from %s :: %s, translated from the Chinese original for repository "
                  "language compliance; %s" % (A_POOL, field, english))
    return out


def mean(xs):
    return float(np.mean(np.asarray(xs, dtype=float)))


def sd(xs, ddof):
    xs = np.asarray(xs, dtype=float)
    if xs.size <= ddof:
        return None
    return float(np.std(xs, ddof=ddof))


def rng_seed_for(base_seed, label):
    """Deterministic per-label stream, so adding a comparison cannot shift earlier results."""
    h = 0
    for ch in label:
        h = (h * 131 + ord(ch)) % (2 ** 32)
    return np.random.default_rng((int(base_seed) + h) % (2 ** 32))


def _mean_of_resamples(v, rng, resamples):
    idx = rng.integers(0, v.size, size=(resamples, v.size))
    return v[idx].mean(axis=1)


def _ci(samples):
    lo = float(np.percentile(samples, (100.0 - CI_LEVEL) / 2.0))
    hi = float(np.percentile(samples, 100.0 - (100.0 - CI_LEVEL) / 2.0))
    return lo, hi


def describe(values, resamples, rng_seed, label, source):
    """Mean, dispersion and percentile bootstrap CI for the mean of one arm."""
    v = np.asarray(values, dtype=float)
    samples = _mean_of_resamples(v, rng_seed_for(rng_seed, label), resamples)
    lo, hi = _ci(samples)
    jlo, jhi = _ci(_mean_of_resamples(v, rng_seed_for(JITTER_RNG_SEED, label), resamples))
    n = int(v.size)
    s1 = sd(v, 1)
    return {
        "n": n,
        "mean": mean(v),
        "median": float(np.median(v)),
        "min": float(v.min()),
        "max": float(v.max()),
        "sd_ddof1_sample": s1,
        "sd_ddof0_population": sd(v, 0),
        "se_of_mean_ddof1": (s1 / np.sqrt(n)) if s1 is not None else None,
        "ci95_percentile": [lo, hi],
        "ci95_halfwidth": (hi - lo) / 2.0,
        "mc_jitter_max_endpoint_shift": max(abs(lo - jlo), abs(hi - jhi)),
        "values": [float(x) for x in v],
        "source": source,
    }


def describe_paired(a, b, resamples, rng_seed, label, source, pairs=None):
    """Percentile bootstrap CI for mean(a) - mean(b), resampling the pairs together."""
    va = np.asarray(a, dtype=float)
    vb = np.asarray(b, dtype=float)
    if va.size != vb.size:
        raise ValueError("%s: paired bootstrap needs equal group sizes (%d vs %d)"
                         % (label, va.size, vb.size))
    d = va - vb
    samples = _mean_of_resamples(d, rng_seed_for(rng_seed, label), resamples)
    lo, hi = _ci(samples)
    jlo, jhi = _ci(_mean_of_resamples(d, rng_seed_for(JITTER_RNG_SEED, label), resamples))
    n = int(d.size)
    s1 = sd(d, 1)
    return {
        "n_pairs": n,
        "pairs": pairs,
        "mean_difference": mean(d),
        "sd_of_differences_ddof1": s1,
        "se_of_mean_difference_ddof1": (s1 / np.sqrt(n)) if s1 is not None else None,
        "ci95_percentile": [lo, hi],
        "ci95_excludes_zero": bool(lo > 0.0 or hi < 0.0),
        "bootstrap_share_difference_le_zero": float(np.mean(samples <= 0.0)),
        "bootstrap_share_difference_ge_zero": float(np.mean(samples >= 0.0)),
        "mc_jitter_max_endpoint_shift": max(abs(lo - jlo), abs(hi - jhi)),
        "per_pair_differences": [float(x) for x in d],
        "pair_signs": ["negative" if x < 0 else ("positive" if x > 0 else "zero") for x in d],
        "n_pairs_negative": int(np.sum(d < 0)),
        "n_pairs_positive": int(np.sum(d > 0)),
        "source": source,
    }


def tost_paired(a, b, margin, source):
    """Two one-sided paired t-tests against +/- margin, plus the smallest equivalent margin."""
    from scipy import stats

    va = np.asarray(a, dtype=float)
    vb = np.asarray(b, dtype=float)
    d = va - vb
    n = int(d.size)
    df = n - 1
    m = float(d.mean())
    s = float(np.std(d, ddof=1))
    se = s / np.sqrt(n)
    t_lower = (m + margin) / se          # H0: mean difference <= -margin
    t_upper = (m - margin) / se          # H0: mean difference >= +margin
    p_lower = float(stats.t.sf(t_lower, df))
    p_upper = float(stats.t.cdf(t_upper, df))
    p_tost = max(p_lower, p_upper)
    tcrit = float(stats.t.ppf(1.0 - ALPHA / 2.0, df))
    ci_lo, ci_hi = m - tcrit * se, m + tcrit * se
    smallest = max(abs(ci_lo), abs(ci_hi))
    return {
        "test": "TOST, two one-sided paired t-tests, alpha = %.2f, df = %d" % (ALPHA, df),
        "n_pairs": n,
        "mean_difference": m,
        "sd_of_differences_ddof1": s,
        "se_of_mean_difference_ddof1": se,
        "ci95_paired_t": [ci_lo, ci_hi],
        "margin": margin,
        "t_for_lower_bound": float(t_lower),
        "t_for_upper_bound": float(t_upper),
        "p_lower": p_lower,
        "p_upper": p_upper,
        "p_tost": p_tost,
        "equivalent_at_margin": bool(p_tost < ALPHA),
        "equivalence_ci_within_margin": bool(ci_lo > -margin and ci_hi < margin),
        "smallest_equivalent_margin": float(smallest),
        "smallest_equivalent_margin_definition":
            "smallest margin at which the paired TOST passes, i.e. max(|CI lower|, |CI upper|) of the "
            "95% paired t interval",
        "source": source,
    }


def welch(a, b, source):
    """Archived-style unpaired Welch test, reproduced here so the printed p value is traceable."""
    from scipy import stats

    va = np.asarray(a, dtype=float)
    vb = np.asarray(b, dtype=float)
    t, p = stats.ttest_ind(va, vb, equal_var=False)
    na, nb = va.size, vb.size
    va1, vb1 = va.var(ddof=1), vb.var(ddof=1)
    se2 = va1 / na + vb1 / nb
    df = se2 ** 2 / ((va1 / na) ** 2 / (na - 1) + (vb1 / nb) ** 2 / (nb - 1))
    return {
        "test": "Welch two-sample t-test (unpaired), two-sided",
        "welch_t": float(t),
        "df": float(df),
        "p_two_sided": float(p),
        "source": source,
    }


