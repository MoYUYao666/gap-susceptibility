# -*- coding: utf-8 -*-
r"""Summarise the classification probe (second task) into macros."""
import glob
import io
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    rows = {}
    for p in glob.glob(os.path.join(ROOT, "runs", "classification_probe", "*.json")):
        d = json.loads(io.open(p, encoding="utf-8").read())
        for arm, rec in d.items():
            rows[arm] = rec["accuracy"]
    if not rows:
        print("no probe results yet")
        return 0
    macros = ["% Generated by scripts/analyse_probe.py from runs/classification_probe/*.json."]
    for arm, acc in sorted(rows.items()):
        macros.append("\\newcommand{\\probe%s}{%.3f}" % (arm, acc))
    io.open(os.path.join(ROOT, "draft", "probe_numbers.tex"), "w", encoding="utf-8", newline="").write("\n".join(macros) + "\n")
    for arm, acc in sorted(rows.items()):
        print("  %-10s accuracy %.4f" % (arm, acc))
    print("wrote draft/probe_numbers.tex")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
