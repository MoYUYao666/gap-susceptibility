# -*- coding: utf-8 -*-
r"""Summarise full-corpus arm runs (no budget ceiling) into a table and macros."""
import glob
import io
import json
import os
import statistics as st

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DS = {"rsicd": "RSICD", "nwpu_captions": "NWPU-Captions"}
LABEL = {"human": "Human captions", "segmented": "Parsed-object", "templated": "Templated", "metadata": "Metadata",
         "humanrich": "Human-rich", "llmcaption": "LLM (Qwen3-VL-8B)", "llmcaption2": "LLM (MiniCPM-V-2.6)"}


def main():
    rows = {}
    for p in glob.glob(os.path.join(ROOT, "runs", "fullarm_*", "*.json")):
        rec = json.loads(io.open(p, encoding="utf-8").read())
        stem = os.path.basename(p)[:-5]
        parts = stem.split("_")
        seed = int(parts[-1][1:])
        arm = parts[-2]
        dataset = "_".join(parts[:-2])
        rows.setdefault((dataset, arm), []).append(rec["metrics"]["R@1_i2t"])
    out = {}
    for (ds, arm), vals in sorted(rows.items()):
        out.setdefault(ds, []).append({"arm": arm, "label": LABEL.get(arm, arm), "n": len(vals),
                                       "mean": round(st.mean(vals), 4),
                                       "sd": round(st.stdev(vals), 4) if len(vals) > 1 else 0.0})
    for ds in out:
        out[ds].sort(key=lambda r: -r["mean"])
    io.open(os.path.join(ROOT, "analysis", "fullarm.json"), "w", encoding="utf-8", newline="").write(
        json.dumps({"note": "full-corpus arms, joint site", "datasets": out}, indent=1))
    lines = [r"\begin{table}[t]", r"\centering", r"\setlength{\tabcolsep}{3pt}", r"\footnotesize",
             r"\caption{Every image instead of a budget: the full-corpus comparison including the LLM arms. Mean $\pm$ "
             r"standard deviation of R@1 (image$\rightarrow$text), joint site.}",
             r"\label{tab:fullarm}",
             r"\begin{tabular}{@{}llc@{}}", r"\hline", r"Dataset & Text provenance & R@1 \\", r"\hline"]
    macros = ["% Generated by scripts/analyse_fullarm.py."]
    for ds, items in out.items():
        first = True
        for r in items:
            lines.append("%s & %s & %.3f $\\pm$ %.3f \\\\" % (DS.get(ds, ds) if first else "", r["label"], r["mean"], r["sd"]))
            first = False
            key = "fr" + ds.replace("_", "") + r["arm"].replace("llmcaption2", "llmcaptionb")
            macros.append("\\newcommand{\\%s}{%.3f}" % (key, r["mean"]))
            macros.append("\\newcommand{\\%sSd}{%.3f}" % (key, r["sd"]))
        lines.append(r"\hline")
    lines += [r"\end{tabular}", r"\end{table}"]
    io.open(os.path.join(ROOT, "draft", "table_fullarm.tex"), "w", encoding="utf-8", newline="").write("\n".join(lines) + "\n")
    io.open(os.path.join(ROOT, "draft", "fullarm_numbers.tex"), "w", encoding="utf-8", newline="").write("\n".join(macros) + "\n")
    for ds, items in out.items():
        print("==", ds)
        for r in items:
            print("  %-12s n=%d %.4f +- %.4f" % (r["arm"], r["n"], r["mean"], r["sd"]))
    print("wrote analysis/fullarm.json, draft/table_fullarm.tex, draft/fullarm_numbers.tex")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
