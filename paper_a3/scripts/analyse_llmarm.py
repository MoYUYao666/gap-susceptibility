# -*- coding: utf-8 -*-
r"""Summarise the matched 3,000-image LLM-caption comparison (four arms x two seeds)."""
import glob
import io
import json
import os
import statistics as st

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LABEL = {"human": "Human captions", "templated": "Templated", "metadata": "Metadata", "llmcaption": "LLM captions"}


def main():
    datasets = {
        "rsicd": ("runs/llmarm_3k", "RSICD (3,000 images)"),
        "nwpu_captions": ("runs/llmarm_968_nwpu", "NWPU-Captions (968 images)"),
    }
    summary = {}
    table_rows = []
    macros = ["% Generated by scripts/analyse_llmarm.py from the matched-subset runs."]
    for ds, (rundir, label) in datasets.items():
        rows = {}
        for p in sorted(glob.glob(os.path.join(ROOT, rundir, "*.json"))):
            rec = json.loads(io.open(p, encoding="utf-8").read())
            arm = os.path.basename(p).split("_")[0]
            rows.setdefault(arm, []).append(rec["metrics"]["R@1_i2t"])
        if not rows:
            continue
        orders = []
        for arm, r1 in rows.items():
            mean = round(st.mean(r1), 4)
            sd = round(st.stdev(r1), 4) if len(r1) > 1 else 0.0
            orders.append({"arm": arm, "label": LABEL.get(arm, arm), "n": len(r1),
                           "R@1_mean": mean, "R@1_sd": sd, "values": r1})
            key = "llm" + ds.replace("_", "") + arm
            macros.append("\\newcommand{\\%sRone}{%.3f}" % (key, mean))
            macros.append("\\newcommand{\\%sSd}{%.3f}" % (key, sd))
        orders.sort(key=lambda r: -r["R@1_mean"])
        summary[ds] = orders
        table_rows.append((label, orders))
    io.open(os.path.join(ROOT, "analysis", "llm_arm.json"), "w", encoding="utf-8", newline="").write(
        json.dumps({"note": "matched subsets, joint site", "datasets": summary}, indent=1))

    lines = [r"\begin{table}[t]", r"\centering", r"\footnotesize",
             r"\caption{The LLM-caption arm on matched subsets (local Qwen3-VL-8B, one sentence per image; every arm "
             r"retrained on exactly the same images, joint site). Mean $\pm$ standard deviation of R@1 "
             r"(image$\rightarrow$text); comparisons are within a subset.}",
             r"\label{tab:llmarm}",
             r"\begin{tabular}{@{}llc@{}}", r"\hline",
             r"Dataset & Text provenance & R@1 \\", r"\hline"]
    for label, orders in table_rows:
        first = True
        for r in orders:
            lines.append("%s & %s & %.3f $\\pm$ %.3f \\\\" % (label if first else "", r["label"], r["R@1_mean"], r["R@1_sd"]))
            first = False
        lines.append(r"\hline")
    lines += [r"\end{tabular}", r"\end{table}"]
    io.open(os.path.join(ROOT, "draft", "table_llmarm.tex"), "w", encoding="utf-8", newline="").write("\n".join(lines) + "\n")
    io.open(os.path.join(ROOT, "draft", "llmarm_numbers.tex"), "w", encoding="utf-8", newline="").write("\n".join(macros) + "\n")
    for ds, orders in summary.items():
        print("==", ds)
        for r in orders:
            print("  %-10s n=%d R@1 %.4f +- %.4f" % (r["arm"], r["n"], r["R@1_mean"], r["R@1_sd"]))
    print("wrote analysis/llm_arm.json, draft/table_llmarm.tex, draft/llmarm_numbers.tex")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
