# -*- coding: utf-8 -*-
r"""Budget macros: the effective number of training pairs per arm on RSITMD.

The derived arms can only supply one text per image, so on RSITMD the human arm trains on more pairs than the
derived arms. These two macros make that ceiling a generated number rather than a hand-typed one.

Outputs draft/budget_numbers.tex with \rsitmdHumanPairs and \rsitmdDerivedPairs.
"""
import glob
import io
import json
import os
import statistics

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def pairs_for(prefix):
    vals = []
    for p in glob.glob(os.path.join(ROOT, "runs", "full_10k", "*.json")):
        name = os.path.basename(p)[:-5]
        if not name.startswith(prefix):
            continue
        rec = json.loads(io.open(p, encoding="utf-8").read())
        if rec.get("pairs_used"):
            vals.append(int(rec["pairs_used"]))
    return int(round(statistics.mean(vals))) if vals else 0


def main():
    human = pairs_for("rsitmd_human_")
    derived = [pairs_for("rsitmd_%s_" % arm) for arm in ("segmented", "templated", "metadata")]
    derived_n = int(round(statistics.mean([d for d in derived if d]))) if any(derived) else 0
    lines = [
        "% Generated by scripts/make_budget_macros.py from runs/full_10k/*.json.",
        "\\newcommand{\\rsitmdHumanPairs}{%d}" % human,
        "\\newcommand{\\rsitmdDerivedPairs}{%d}" % derived_n,
    ]
    out = os.path.join(ROOT, "draft", "budget_numbers.tex")
    io.open(out, "w", encoding="utf-8", newline="").write("\n".join(lines) + "\n")
    print("wrote", out, "| human", human, "| derived", derived_n)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
