# -*- coding: utf-8 -*-
r"""Length-control analysis: how much of the human-rich gain is just more tokens?

Reads runs/repeated_10k/*.json (the same human caption repeated five times, matched in length to the human-rich arm)
and writes analysis/repeated.json plus the macros used in the information-density paragraph.
"""
import glob
import io
import json
import os
import statistics as st

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    by_ds = {}
    for p in sorted(glob.glob(os.path.join(ROOT, "runs", "repeated_10k", "*.json"))):
        rec = json.loads(io.open(p, encoding="utf-8").read())
        name = os.path.basename(p)[:-5]
        ds = "rsicd" if name.startswith("rsicd") else "nwpu_captions"
        by_ds.setdefault(ds, []).append(rec["metrics"]["R@1_i2t"])

    rows = []
    for ds, vals in by_ds.items():
        rows.append({"dataset": ds, "n": len(vals), "mean": round(st.mean(vals), 4),
                     "sd": round(st.stdev(vals), 4) if len(vals) > 1 else 0.0, "values": vals})

    io.open(os.path.join(ROOT, "analysis", "repeated.json"), "w", encoding="utf-8", newline="").write(
        json.dumps({"note": "length control: one human caption repeated five times, 10k pairs, site both, seeds 0-2",
                    "rows": rows}, indent=1))

    macros = ["% Generated by scripts/analyse_repeated.py from runs/repeated_10k/*.json."]
    for r in rows:
        key = "repeated" + r["dataset"].replace("_", "")
        macros.append("\\newcommand{\\%s}{%.3f}" % (key, r["mean"]))
        macros.append("\\newcommand{\\%sSd}{%.3f}" % (key, r["sd"]))
    io.open(os.path.join(ROOT, "draft", "repeated_numbers.tex"), "w", encoding="utf-8", newline="").write(
        "\n".join(macros) + "\n")
    for r in rows:
        print("  %-16s n=%d mean %.4f sd %.4f" % (r["dataset"], r["n"], r["mean"], r["sd"]))
    print("wrote analysis/repeated.json and draft/repeated_numbers.tex")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
